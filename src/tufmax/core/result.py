"""
TUFMax Result Container (Refined for LoS Support).

This module defines the TUFMaxResult class, updated to handle both traditional 
vertical profiles and complex Line-of-Sight (LoS) trajectories generated by the engine.
"""

from __future__ import annotations
from typing import Dict, Any, Optional, Union, List, Tuple
from dataclasses import dataclass, field
import numpy as np
import astropy.units as u
from astropy.units import Quantity
import warnings

# Local imports
from .validator import ValidationReport
# Circular import handling: Import type only if needed, or pass object directly
# from .io.los_path import LoSProfile 

@dataclass(frozen=True)
class TUFMaxResult:
    """
    Immutable Container for TUFMax Simulation Results.
    
    Updated to support:
    1. Traditional Vertical Profiles (Altitude-based)
    2. Line-of-Sight (LoS) Trajectories (Path-based)
    """
    
    # Core Profile Axis (Optional if LoS is present)
    altitude: Optional[Quantity] = None
    
    # Physics Categories (Dicts of Quantities or Arrays)
    neutral_data: Dict[str, Any] = field(default_factory=dict)
    plasma_data: Dict[str, Any] = field(default_factory=dict)
    magnetic_data: Dict[str, Any] = field(default_factory=dict)
    derived_data: Dict[str, Any] = field(default_factory=dict)
    
    # NEW: LoS Geometry Data
    los_profile: Optional[Any] = field(default=None, repr=False) # Store LoSProfile object
    
    # Metadata & Provenance
    metadata: Dict[str, Any] = field(default_factory=dict)
    validation_report: Optional[ValidationReport] = None
    model_chain: Dict[int, str] = field(default_factory=dict)
    
    # Internal Mask (Global validity)
    _valid_mask: Optional[np.ndarray] = field(default=None, repr=False)

    def __post_init__(self):
        """Validates consistency between Altitude and LoS modes."""
        if self.altitude is None and self.los_profile is None:
            # Allow empty result for initialization, but warn if used
            pass
        
        # Initialize mask if not provided
        if self._valid_mask is None:
            length = 0
            if self.altitude is not None:
                length = len(self.altitude)
            elif self.los_profile is not None:
                length = self.los_profile.n_points
            
            if length > 0:
                object.__setattr__(self, '_valid_mask', np.ones(length, dtype=bool))

    # ----------------------------------------------------------------------
    # Accessor Properties
    # ----------------------------------------------------------------------

    @property
    def valid_mask(self) -> np.ndarray:
        if self._valid_mask is None:
            return np.array([], dtype=bool)
        return self._valid_mask

    @property
    def n_points(self) -> int:
        if self.altitude is not None:
            return len(self.altitude)
        if self.los_profile is not None:
            return self.los_profile.n_points
        return 0

    @property
    def effective_altitude(self) -> Optional[Quantity]:
        """
        Returns the altitude array. 
        If in LoS mode, extracts altitude from the path geometry.
        """
        if self.altitude is not None:
            return self.altitude
        if self.los_profile is not None:
            return self.los_profile.geodetic['alt']
        return None

    # ----------------------------------------------------------------------
    # LoS Specific Utilities
    # ----------------------------------------------------------------------

    def flatten_to_vertical(self) -> 'TUFMaxResult':
        """
        Converts an LoS-based result into a traditional vertical profile result.
        
        This method extracts valid points from the LoS trajectory, sorts them by 
        altitude, and creates a new TUFMaxResult compatible with standard 1D physics modules.
        
        Returns:
            A new TUFMaxResult instance structured as a vertical profile.
        """
        if self.los_profile is None:
            return self # Already vertical or empty

        # Get valid data from LoS
        valid_data = self.los_profile.get_valid_profile()
        
        if valid_data['count'] == 0:
            raise ValueError("No valid points in LoS profile to flatten.")

        # Extract arrays
        altitudes = valid_data['geodetic']['alt']
        mask = valid_data['count'] > 0 # All returned are valid
        
        # Sort by altitude for consistency
        sort_idx = np.argsort(altitudes.value)
        sorted_alt = altitudes[sort_idx]
        
        # Note: We cannot easily sort other physics data here because they haven't been calculated yet.
        # This method is primarily useful to prepare the GEOMETRY for the physics engine.
        # The physics engine will then populate neutral_data, etc., aligned with sorted_alt.
        
        return TUFMaxResult(
            altitude=sorted_alt,
            neutral_data={}, # To be filled by physics blocks
            plasma_data={},
            magnetic_data={}, # Can copy averaged B if needed
            derived_data={},
            metadata={**self.metadata, 'source': 'LoS_Flattened'},
            validation_report=self.validation_report,
            model_chain=self.model_chain,
            _valid_mask=np.ones(len(sorted_alt), dtype=bool)
        )

    # ----------------------------------------------------------------------
    # Export Methods (Updated for LoS)
    # ----------------------------------------------------------------------

    def to_dataframe(self, include_invalid: bool = False) -> 'pd.DataFrame':
        try:
            import pandas as pd
        except ImportError:
            raise ImportError("Pandas required.")

        # Determine source of truth
        if self.los_profile is not None:
            # LoS Mode: Use full path data
            data = self.los_profile.get_valid_profile() if not include_invalid else {
                'xyz': self.los_profile.xyz,
                'geodetic': self.los_profile.geodetic,
                'magnetic': self.los_profile.magnetic
            }
            
            df_dict = {
                'x_m': data['xyz'][:, 0].value,
                'y_m': data['xyz'][:, 1].value,
                'z_m': data['xyz'][:, 2].value,
                'lat_deg': data['geodetic']['lat'].value,
                'lon_deg': data['geodetic']['lon'].value,
                'alt_km': data['geodetic']['alt'].value,
                'mag_lat': data['magnetic']['MagLat'].value,
                'mlt': data['magnetic']['MLT'].value,
            }
        elif self.altitude is not None:
            # Vertical Mode
            df_dict = {'altitude_km': self.altitude.to(u.km).value}
        else:
            return pd.DataFrame()

        # Add physics data if present
        # ... (lógica existente para agregar neutral_data, etc.) ...
        
        df = pd.DataFrame(df_dict)
        return df

    def summary(self) -> str:
        base_summary = [
            "TUFMax Execution Summary",
            "=" * 40,
            f"Mode: {'Line-of-Sight' if self.los_profile else 'Vertical'}",
            f"Points: {self.n_points}",
            f"Status: {self.validation_report.status.value if self.validation_report else 'N/A'}",
        ]
        
        # Obtener array de altitudes seguro
        alt_array = self.effective_altitude
        
        if alt_array is not None and len(alt_array) > 0:
            # EXTRAER VALORES EXPLÍCITAMENTE COMO FLOATS
            try:
                start_val = float(alt_array[0].to(u.km).value)
                end_val = float(alt_array[-1].to(u.km).value)
                base_summary.append(f"Alt Range: {start_val:.2f} km to {end_val:.2f} km")
            except (AttributeError, TypeError, ValueError) as e:
                base_summary.append(f"Alt Range: ERROR PARSING ({e})")
        elif self.los_profile:
             # Fallback si effective_altitude falla pero hay los_profile
             try:
                g_alt = self.los_profile.geodetic.get('alt')
                if g_alt is not None:
                    base_summary.append(f"LoS Range: {float(g_alt[0].to(u.km).value):.1f} km -> {float(g_alt[-1].to(u.km).value):.1f} km")
             except Exception:
                base_summary.append("LoS Range: UNAVAILABLE")
            
        return "\n".join(base_summary)

    def __repr__(self):
        mode = "LoS" if self.los_profile else "Vertical"
        return f"TUFMaxResult(Mode={mode}, Points={self.n_points})"
